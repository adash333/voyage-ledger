import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
test('TRADE-SAVE-UI-001: export JSON, restart, import and continue mid-game',async({page})=>{
 await page.goto('/trade/');await page.getByRole('button',{name:'スキップ'}).click();
 await page.locator('#good').selectOption('glass');await page.locator('#qty').fill('3');
 await page.locator('#checkTrade').click();await page.locator('#tradePreview #accept').click();
 await page.locator('#checkSail').click();await page.locator('#sailPreview #accept').click();
 await expect(page.locator('#summary')).toContainText('金貨80枚');
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'データをJSON形式で保存'}).click()]);
 expect(download.suggestedFilename()).toMatch(/^voyage-trade-\d{8}-\d{4}\.json$/);
 const path=await download.path();
 const data=JSON.parse(readFileSync(path,'utf8'));
 expect(data.app).toBe('voyage-ledger-trade');
 expect(data.state.events).toHaveLength(2);
 await expect(page.locator('#saveMessage')).toContainText('保存しました');
 // Start over, then bring the file back.
 await page.locator('#tab-trade').click();
 for(let i=0;i<2;i++){await page.locator('#checkSail').click();await page.locator('#sailPreview #accept').click();}
 page.once('dialog',d=>d.accept());await page.locator('#closeBtn').click();
 page.once('dialog',d=>d.accept());await page.locator('#restartBtn').click();
 await expect(page.locator('#summary')).toContainText('金貨100枚');
 await expect(page.locator('#summary')).toContainText('ヴェネツィア');
 page.once('dialog',d=>{expect(d.message()).toContain('第1航海');d.accept();});
 await page.locator('#importFile').setInputFiles(path);
 await expect(page.locator('#saveMessage')).toContainText('読み込みました');
 await expect(page.locator('#summary')).toContainText('金貨80枚');
 await expect(page.locator('#summary')).toContainText('アレクサンドリア');
 await expect(page.locator('#holding')).toContainText('ガラス製品 3');
 await page.reload();
 await expect(page.locator('#summary')).toContainText('金貨80枚');
 await expect(page.locator('#summary')).toContainText('アレクサンドリア');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
test('TRADE-SAVE-UI-002: cancelled, invalid and tampered imports leave the game unchanged',async({page})=>{
 await page.goto('/trade/');await page.getByRole('button',{name:'スキップ'}).click();
 await page.locator('#good').selectOption('pepper');await page.locator('#qty').fill('2');
 await page.locator('#checkTrade').click();await page.locator('#tradePreview #accept').click();
 await expect(page.locator('#summary')).toContainText('金貨82枚');
 const saved=await page.evaluate(()=>localStorage.getItem('voyage-trade-v1'));
 const file=(name,body)=>({name,mimeType:'application/json',buffer:Buffer.from(body)});
 await page.locator('#importFile').setInputFiles(file('broken.json','{oops'));
 await expect(page.locator('#saveMessage')).toContainText('JSONファイルとして読み込めませんでした');
 await page.locator('#importFile').setInputFiles(file('other.json',JSON.stringify({app:'something-else'})));
 await expect(page.locator('#saveMessage')).toContainText('このゲームのセーブデータではありません');
 const forged=JSON.parse(saved);forged.events[0].price=1;
 await page.locator('#importFile').setInputFiles(file('forged.json',JSON.stringify({app:'voyage-ledger-trade',format:1,state:forged})));
 await expect(page.locator('#saveMessage')).toContainText('形式が正しくありません');
 const fresh={version:1,voyage:1,stop:0,status:'active',events:[]};
 page.once('dialog',d=>d.dismiss());
 await page.locator('#importFile').setInputFiles(file('fresh.json',JSON.stringify({app:'voyage-ledger-trade',format:1,state:fresh})));
 await page.waitForTimeout(300);
 await expect(page.locator('#summary')).toContainText('金貨82枚');
 expect(await page.evaluate(()=>localStorage.getItem('voyage-trade-v1'))).toBe(saved);
});
